-- Creates the database only if it does not exist. The option block below is applied on creation
-- only, so re-running never resets settings on an existing database (e.g. Query Store, recovery model).
-- Variables come from 09_deployment\config.sql.
USE [master]
GO
IF DB_ID(N'$(DatabaseName)') IS NULL
BEGIN
CREATE DATABASE [$(DatabaseName)]
 CONTAINMENT = NONE
 ON  PRIMARY 
( NAME = N'$(DatabaseName)', FILENAME = N'$(DataPath)\$(DatabaseName).mdf' , SIZE = 73728KB , MAXSIZE = UNLIMITED, FILEGROWTH = 65536KB )
 LOG ON 
( NAME = N'$(DatabaseName)_log', FILENAME = N'$(LogPath)\$(DatabaseName)_log.ldf' , SIZE = 73728KB , MAXSIZE = 2048GB , FILEGROWTH = 65536KB )
 WITH CATALOG_COLLATION = DATABASE_DEFAULT;
ALTER DATABASE [$(DatabaseName)] SET COMPATIBILITY_LEVEL = 150;
IF (1 = FULLTEXTSERVICEPROPERTY('IsFullTextInstalled'))
begin
EXEC [$(DatabaseName)].[dbo].[sp_fulltext_database] @action = 'enable'
end;
ALTER DATABASE [$(DatabaseName)] SET ANSI_NULL_DEFAULT OFF;
ALTER DATABASE [$(DatabaseName)] SET ANSI_NULLS OFF;
ALTER DATABASE [$(DatabaseName)] SET ANSI_PADDING OFF;
ALTER DATABASE [$(DatabaseName)] SET ANSI_WARNINGS OFF;
ALTER DATABASE [$(DatabaseName)] SET ARITHABORT OFF;
ALTER DATABASE [$(DatabaseName)] SET AUTO_CLOSE OFF;
ALTER DATABASE [$(DatabaseName)] SET AUTO_SHRINK OFF;
ALTER DATABASE [$(DatabaseName)] SET AUTO_UPDATE_STATISTICS ON;
ALTER DATABASE [$(DatabaseName)] SET CURSOR_CLOSE_ON_COMMIT OFF;
ALTER DATABASE [$(DatabaseName)] SET CURSOR_DEFAULT  GLOBAL;
ALTER DATABASE [$(DatabaseName)] SET CONCAT_NULL_YIELDS_NULL OFF;
ALTER DATABASE [$(DatabaseName)] SET NUMERIC_ROUNDABORT OFF;
ALTER DATABASE [$(DatabaseName)] SET QUOTED_IDENTIFIER OFF;
ALTER DATABASE [$(DatabaseName)] SET RECURSIVE_TRIGGERS OFF;
ALTER DATABASE [$(DatabaseName)] SET  DISABLE_BROKER;
ALTER DATABASE [$(DatabaseName)] SET AUTO_UPDATE_STATISTICS_ASYNC OFF;
ALTER DATABASE [$(DatabaseName)] SET DATE_CORRELATION_OPTIMIZATION OFF;
ALTER DATABASE [$(DatabaseName)] SET TRUSTWORTHY OFF;
ALTER DATABASE [$(DatabaseName)] SET ALLOW_SNAPSHOT_ISOLATION OFF;
ALTER DATABASE [$(DatabaseName)] SET PARAMETERIZATION SIMPLE;
ALTER DATABASE [$(DatabaseName)] SET READ_COMMITTED_SNAPSHOT OFF;
ALTER DATABASE [$(DatabaseName)] SET HONOR_BROKER_PRIORITY OFF;
ALTER DATABASE [$(DatabaseName)] SET RECOVERY FULL;
ALTER DATABASE [$(DatabaseName)] SET  MULTI_USER;
ALTER DATABASE [$(DatabaseName)] SET PAGE_VERIFY CHECKSUM;
ALTER DATABASE [$(DatabaseName)] SET DB_CHAINING OFF;
ALTER DATABASE [$(DatabaseName)] SET FILESTREAM( NON_TRANSACTED_ACCESS = OFF );
ALTER DATABASE [$(DatabaseName)] SET TARGET_RECOVERY_TIME = 60 SECONDS;
ALTER DATABASE [$(DatabaseName)] SET DELAYED_DURABILITY = DISABLED;
ALTER DATABASE [$(DatabaseName)] SET ACCELERATED_DATABASE_RECOVERY = OFF;
EXEC sys.sp_db_vardecimal_storage_format N'$(DatabaseName)', N'ON';
ALTER DATABASE [$(DatabaseName)] SET QUERY_STORE = OFF;
ALTER DATABASE [$(DatabaseName)] SET  READ_WRITE;
END
GO
